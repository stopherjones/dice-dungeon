export interface TableRow<T = any> {
  minRoll: number;
  maxRoll: number;
  id: string;
  name: string;
  subtitle?: string;
  description: string;
  icon: string;
  badge?: string;
  data: T;
}

export interface RollableTable<T = any> {
  id: string;
  title: string;
  diceFormula: string; // e.g. "1d6", "1d20", "1d100"
  diceSides: number;
  diceCount: number;
  description: string;
  rows: TableRow<T>[];
}

